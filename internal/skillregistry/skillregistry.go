// Package skillregistry scans project and user-level skill directories and
// renders .atl/skill-registry.md: the cross-tool index that lets a delegator
// hand a freshly spawned subagent exact SKILL.md paths. Subagents start with
// no visibility into a project's own skills/ directory (confirmed empirically
// — Claude Code's native skill discovery only covers .claude/skills, plugin,
// and user-level skills, never an arbitrary project directory), so this index
// is the only way delegators resolve project skills for sub-delegation.
package skillregistry

import (
	"crypto/sha1"
	"encoding/hex"
	"encoding/json"
	"fmt"
	"os"
	"path/filepath"
	"sort"
	"strings"
	"time"

	"gopkg.in/yaml.v3"
)

// userSkillDirs are the user-level skill roots scanned in fixed order,
// relative to the caller's home directory. The project's own skills/ dir is
// always scanned first and always wins a name collision; among these roots,
// the earlier entry wins (skills/skill-registry/SKILL.md Decision Gates).
var userSkillDirs = []string{
	".pi/agent/skills",
	".agents/skills",
	".config/opencode/skills",
	".claude/skills",
	".codex/skills",
}

// skip reports whether a skill directory name is never indexed: sdd-<phase>
// skills are instruction-embedded directly into each archon-<phase> subagent
// body (never resolved through the registry), _shared is a references-only
// module with no activation contract, and skill-registry would be
// self-referential.
func skip(name string) bool {
	return strings.HasPrefix(name, "sdd-") || name == "_shared" || name == "skill-registry"
}

type frontmatter struct {
	Name        string `yaml:"name"`
	Description string `yaml:"description"`
}

// Entry is one row of the rendered registry table.
type Entry struct {
	Name        string
	Description string
	Scope       string // "project" or "user"
	Path        string // absolute path to the skill's SKILL.md
}

// Result is a completed scan, ready to render or write.
type Result struct {
	Entries []Entry
	Sources []string // absolute user-level roots scanned, in scan order
}

// Refresh scans <projectDir>/skills plus the fixed user-level roots under
// homeDir for "*/SKILL.md" (one level deep, matching the embed glob pattern
// used elsewhere in this codebase), and returns a result deduplicated by
// skill name in scan order: project first, then each user root in the fixed
// order above. homeDir is a parameter (not os.UserHomeDir() called inside)
// so callers can scan a project without also picking up the real machine's
// user-level skills — tests pass a temp dir; the CLI passes the real home.
func Refresh(projectDir, homeDir string) (*Result, error) {
	byName := make(map[string]Entry)
	var names []string

	scanDir := func(dir, scope string) {
		entries, err := os.ReadDir(dir)
		if err != nil {
			return // a missing root is not an error — nothing to scan
		}
		for _, e := range entries {
			if !e.IsDir() || skip(e.Name()) {
				continue
			}
			skillMD := filepath.Join(dir, e.Name(), "SKILL.md")
			data, err := os.ReadFile(skillMD)
			if err != nil {
				continue
			}
			fm, err := parseFrontmatter(data)
			if err != nil || fm.Name == "" {
				continue
			}
			if _, exists := byName[fm.Name]; exists {
				continue // earlier source in scan order already claimed this name
			}
			byName[fm.Name] = Entry{
				Name:        fm.Name,
				Description: fm.Description,
				Scope:       scope,
				Path:        skillMD,
			}
			names = append(names, fm.Name)
		}
	}

	scanDir(filepath.Join(projectDir, "skills"), "project")

	var sources []string
	if homeDir != "" {
		for _, rel := range userSkillDirs {
			abs := filepath.Join(homeDir, rel)
			sources = append(sources, abs)
			scanDir(abs, "user")
		}
	}

	sort.Strings(names)
	result := &Result{Sources: sources}
	for _, n := range names {
		result.Entries = append(result.Entries, byName[n])
	}
	return result, nil
}

func parseFrontmatter(data []byte) (frontmatter, error) {
	var fm frontmatter
	s := string(data)
	if !strings.HasPrefix(s, "---\n") {
		return fm, fmt.Errorf("no frontmatter")
	}
	rest := s[len("---\n"):]
	end := strings.Index(rest, "\n---")
	if end == -1 {
		return fm, fmt.Errorf("unterminated frontmatter")
	}
	if err := yaml.Unmarshal([]byte(rest[:end]), &fm); err != nil {
		return fm, err
	}
	return fm, nil
}

// Render produces the markdown body of .atl/skill-registry.md for projectName
// at the given timestamp. The structure (headings, table columns, loading
// protocol) is the contract skills/_shared/skill-resolver.md and
// skills/judgment-day already depend on — keep it byte-compatible with theirs.
func Render(projectName string, res *Result, now time.Time) string {
	var b strings.Builder

	fmt.Fprintf(&b, "# Skill Registry — %s\n\n", projectName)
	b.WriteString("<!-- Auto-generated by archon skill-registry refresh. Run `archon skill-registry refresh --force` to regenerate. -->\n\n")
	fmt.Fprintf(&b, "Last updated: %s\n\n", now.Format("2006-01-02"))

	b.WriteString("## Sources scanned\n\n")
	for _, s := range res.Sources {
		fmt.Fprintf(&b, "- %s\n", s)
	}
	b.WriteString("\n")

	b.WriteString("## Contract\n\n")
	b.WriteString("**Delegator use only.** This registry is an index, not a summary. Any agent that launches subagents reads it to select relevant skills, then passes exact `SKILL.md` paths for the subagent to read before work.\n\n")
	b.WriteString("`SKILL.md` remains the source of truth. Do not inject generated summaries or compact rules by default; pass paths so subagents load the full runtime contract and preserve author intent.\n\n")

	b.WriteString("## Skills\n\n")
	b.WriteString("| Skill | Trigger / description | Scope | Path |\n")
	b.WriteString("| --- | --- | --- | --- |\n")
	for _, e := range res.Entries {
		fmt.Fprintf(&b, "| `%s` | %s | %s | `%s` |\n", e.Name, e.Description, e.Scope, e.Path)
	}
	b.WriteString("\n")

	b.WriteString("## Loading protocol\n\n")
	b.WriteString("1. Match task context and target files against the `Trigger / description` column.\n")
	b.WriteString("2. Pass only the matching `Path` values to the subagent under `## Skills to load before work`.\n")
	b.WriteString("3. Instruct the subagent to read those exact `SKILL.md` files before reading, writing, reviewing, testing, or creating artifacts.\n")
	b.WriteString("4. If no matching skill exists, proceed without project skill injection and report `skill_resolution: none`.\n")

	return b.String()
}

// fingerprint hashes the content that matters for cache-hit detection: which
// skills exist, under what scope and description, and where. It excludes the
// Sources-scanned list and the Last-updated timestamp, so a refresh with an
// unchanged skill set is a cache hit even if the scan touched a root that
// happened not to exist on this run.
func fingerprint(res *Result) string {
	parts := make([]string, 0, len(res.Entries))
	for _, e := range res.Entries {
		parts = append(parts, e.Name+"|"+e.Scope+"|"+e.Path+"|"+e.Description)
	}
	sum := sha1.Sum([]byte(strings.Join(parts, "\n")))
	return hex.EncodeToString(sum[:])
}

type cacheFile struct {
	Fingerprint string `json:"fingerprint"`
}

// Write renders res into <projectDir>/.atl/skill-registry.md and records its
// fingerprint in <projectDir>/.atl/.skill-registry.cache.json. When force is
// false and the computed fingerprint matches the cached one, Write leaves
// both files untouched and reports a cache hit. It returns the path written
// (or that would have been written, on a cache hit) and whether it was a
// cache hit.
func Write(projectDir string, res *Result, force bool, now time.Time) (path string, cacheHit bool, err error) {
	atlDir := filepath.Join(projectDir, ".atl")
	registryPath := filepath.Join(atlDir, "skill-registry.md")
	cachePath := filepath.Join(atlDir, ".skill-registry.cache.json")

	fp := fingerprint(res)

	if !force {
		if data, err := os.ReadFile(cachePath); err == nil {
			var cached cacheFile
			if json.Unmarshal(data, &cached) == nil && cached.Fingerprint == fp {
				return registryPath, true, nil
			}
		}
	}

	if err := os.MkdirAll(atlDir, 0o755); err != nil {
		return "", false, fmt.Errorf("create .atl dir: %w", err)
	}

	content := Render(filepath.Base(projectDir), res, now)
	if err := os.WriteFile(registryPath, []byte(content), 0o644); err != nil {
		return "", false, fmt.Errorf("write skill-registry.md: %w", err)
	}

	cacheData, err := json.MarshalIndent(cacheFile{Fingerprint: fp}, "", "  ")
	if err != nil {
		return "", false, fmt.Errorf("encode cache: %w", err)
	}
	if err := os.WriteFile(cachePath, append(cacheData, '\n'), 0o644); err != nil {
		return "", false, fmt.Errorf("write cache: %w", err)
	}

	return registryPath, false, nil
}
